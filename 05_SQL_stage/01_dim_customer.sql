CREATE VIEW dbo.dim_customer AS
SELECT
    SK_ID_CURR,
    CODE_GENDER,
    FLAG_OWN_CAR,
    FLAG_OWN_REALTY,
    OWN_CAR_AGE,
    CNT_CHILDREN,
    CNT_FAM_MEMBERS,
    NAME_TYPE_SUITE,
    NAME_INCOME_TYPE,
    NAME_EDUCATION_TYPE,
    NAME_FAMILY_STATUS,
    NAME_HOUSING_TYPE,
    OCCUPATION_TYPE,
    ORGANIZATION_TYPE,
    REGION_RATING_CLIENT,
    REGION_RATING_CLIENT_W_CITY,
    REGION_POPULATION_RELATIVE,
    AGE_YEARS,
    YEARS_EMPLOYED,
    DAYS_EMPLOYED_ANOM,     -- flag: employed-days was an outlier/placeholder
    REG_REGION_NOT_LIVE_REGION,
    REG_REGION_NOT_WORK_REGION,
    LIVE_REGION_NOT_WORK_REGION,
    REG_CITY_NOT_LIVE_CITY,
    REG_CITY_NOT_WORK_CITY,
    LIVE_CITY_NOT_WORK_CITY
FROM dbo.raw_application_train;
GO

